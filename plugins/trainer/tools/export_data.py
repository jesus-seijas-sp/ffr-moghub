"""Writes runtime/FFRTrainer/Scripts/game_data.lua from the FFR Save Editor's catalogs (its data folder): which item
ids are consumables and artifacts, which unit ids are enemies, and which maps are real areas (not event stages).
Rerun after the editor's data is updated for a game patch.  usage: python tools/export_data.py [path to ffr-save-editor/data]
(default: an ffr-save-editor checkout next to this repository)"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "..", "..", "ffr-save-editor", "data")
OUT = os.path.join(HERE, "..", "runtime", "FFRTrainer", "Scripts", "game_data.lua")
ARTIFACT_SKIP = {30018}            # no English text in the game files (the editor leaves it out too)


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


items = load("items.json")
consumables = sorted(i["id"] for i in items if i["kind"] == "consumable")
artifacts = sorted(i["id"] for i in items if i["kind"] == "artifact"
                   and i["id"] not in ARTIFACT_SKIP and not re.search(r"\[TEMP\]", i["name"]))
enemies = sorted(int(k) for k in load("journal.json")["enemies"])
maps = sorted(m["id"] for m in load("maps.json") if m["type"] != "event")


def lua_list(ids):
    lines, line = [], []
    for i in ids:
        line.append(str(i))
        if len(line) == 20:
            lines.append("        " + ", ".join(line) + ",")
            line = []
    if line:
        lines.append("        " + ", ".join(line) + ",")
    return "{\n" + "\n".join(lines) + "\n    }"


with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Generated by tools/export_data.py from the FFR Save Editor's catalogs. Don't edit by hand.\n")
    f.write("return {\n")
    for name, ids in (("consumables", consumables), ("artifacts", artifacts), ("enemies", enemies), ("maps", maps)):
        f.write(f"    {name} = {lua_list(ids)},\n")
    f.write("}\n")
print(f"{OUT}: {len(consumables)} consumables, {len(artifacts)} artifacts, {len(enemies)} enemies, {len(maps)} maps")
