"""Write data/travel_data.lua: the world map's landmarks (the places the game's own map can fast travel to) by Bestiary
area, for the area page's "Travel here".

Run from plugins/bestiary:  python tools/export_travel.py
Reads extracted/json/Datatable/Map/DA_MapLandmark.json
      (ffr-dump json FFRS/Content/Datatable/Map/DA_MapLandmark.DA_MapLandmark <that file>),
the map tables in extracted/json/Datatable/Map/MapData, and data/bestiary_data.json (its map -> area grouping).
  areas  area key -> list of landmarks; a landmark is its map versions in the game's order, {map, cond, type}: the
         first whose condition holds is where it leads now (the capital while it burns, then as rebuilt), and a
         version with no map (-1) means it leads nowhere then. type is the map's eMapType name (the game's fast
         travel leaves dungeons out)
  kinds  area key -> what kind of place it is, for its marker on the area page's map: the eMapType name of its maps
         (Town before VisionSmallShrine before Dungeon / Underworld before Field); the world map's island areas are Field
"""
import glob, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from lua_table import lua  # noqa: E402

DT = 'extracted/json/Datatable'


def rows(path):
    d = json.load(open(path, encoding='utf8'))
    return d[0]['Rows'] if isinstance(d, list) else d.get('Rows', d)


map_type = {}
for f in glob.glob(DT + '/Map/MapData/DT_MapData_*.json'):
    for v in rows(f).values():
        map_type[v['ID']] = v['MapType'].split('::')[-1]
area_of = {int(k): v for k, v in json.load(open('data/bestiary_data.json', encoding='utf8'))['mapArea'].items()}

areas = {}
landmarks = json.load(open(DT + '/Map/DA_MapLandmark.json', encoding='utf8'))['Properties']['landmarkDataList']
for lm in landmarks:
    versions = [{'map': x['mapId'], 'cond': x['Condition'] or '', 'type': map_type.get(x['mapId'], '')}
                for x in lm['landmarkDataList']]
    area = next((area_of.get(v['map']) for v in versions if v['map'] >= 0 and area_of.get(v['map'])), None)
    if area:
        areas.setdefault(area, []).append(versions)

RANK = ['Town', 'VisionSmallShrine', 'Dungeon', 'Underworld', 'Field']
kinds = {}
for m, area in area_of.items():
    t = map_type.get(m)
    if t in RANK and (area not in kinds or RANK.index(t) < RANK.index(kinds[area])):
        kinds[area] = t
for area in json.load(open('data/bestiary_data.json', encoding='utf8'))['islandArea'].values():
    kinds[area] = 'Field'

out = 'data/travel_data.lua'
with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('-- generated by tools/export_travel.py; do not edit\nreturn ' + lua({'areas': areas, 'kinds': kinds}) + '\n')
print(f'{out}: {sum(len(l) for l in areas.values())} landmarks in {len(areas)} areas, {len(kinds)} kinds')
