"""Shared by export_data.py, add_unit_extras.py and area_levels.py: the data file as a Lua table, and the per-unit
fields added for Libra+."""
import json


def lua(v, ind=''):
    """the same data as a Lua table, for the plugin (require 'bestiary_data')"""
    if isinstance(v, dict):
        items = [('[%s]' % k if isinstance(k, int) else '[%s]' % json.dumps(k)) + ' = ' + lua(x, ind + ' ') for k, x in v.items()]
        return '{' + ', '.join(items) + '}'
    if isinstance(v, list):
        return '{' + ', '.join(lua(x, ind) for x in v) + '}'
    if v is None:
        return 'nil'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return json.dumps(v)


def unit_extras(v):
    """drop / rare drop / steal rates (DT_UnitParameter keeps them as divisors: the chance is 1 in rate, 0 never)"""
    return {'rate': [v['DropNormalItemRate'], v['DropRareItemRate'], v['StealItemRate']]}


def write_lua(out, path='data/bestiary_data.lua'):
    with open(path, 'w', encoding='utf8') as f:
        f.write('-- generated by tools/export_data.py from data/bestiary_data.json; do not edit\nreturn ' + lua(out) + '\n')
